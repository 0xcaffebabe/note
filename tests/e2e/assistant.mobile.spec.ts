import { test, expect, goto } from './fixtures'
import { persistentBridge } from './ai-bridge-fixture'

test('320px 触屏聊天弹窗：历史切换、工具概览与安全 Markdown 均留在视口，关闭不影响连接', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  const longQuery = 'long-query-'.repeat(12)
  const runtime = await persistentBridge(page, { answer: '## 文档概要\n\n- 支持移动问答\n- 聊天记录保存在 Note Bridge\n\n```js\n    const result = "' + 'long-code-'.repeat(18) + '";\n```\n\n| 特性 | 状态 |\n|---|---|\n| 模型选择 | 可用 |\n\n![不加载远程图片](https://example.invalid/private)' })
  const frames = runtime.frames
  await goto(page, '/home.html')
  const launcher = page.locator('.navigation-launcher')
  await launcher.tap()
  await page.getByRole('button', { name: /^Note Bridge：/ }).tap()
  const bridge = page.getByRole('dialog', { name: 'Note Bridge 连接', exact: true })
  await bridge.getByRole('textbox', { name: '配对码', exact: true }).fill('123456')
  await bridge.getByRole('button', { name: '连接 Note Bridge', exact: true }).tap()
  await expect(bridge.getByText('已连接 Note Bridge', { exact: true })).toBeVisible()
  await bridge.getByRole('button', { name: /关闭|close/i }).tap()
  await launcher.tap()
  await page.getByRole('button', { name: '站点导航与工具', exact: true }).tap()
  await page.getByRole('dialog', { name: '站点导航与工具', exact: true }).getByRole('button', { name: '知识助手', exact: true }).tap()
  const dialog = page.getByRole('dialog', { name: '知识助手', exact: true })
  await expect(dialog.locator('.el-dialog.knowledge-assistant-dialog')).toBeInViewport({ ratio: 1 })
  const panel = await dialog.locator('.knowledge-assistant-dialog').boundingBox()
  expect(Math.abs(panel!.x - (page.viewportSize()!.width - panel!.width) / 2)).toBeLessThan(2)
  expect(Math.abs(panel!.y - (page.viewportSize()!.height - panel!.height) / 2)).toBeLessThan(2)
  await expect(page.locator('.el-drawer:visible')).toHaveCount(0)
  const question = dialog.getByRole('textbox', { name: '你的问题', exact: true })
  const model = dialog.getByRole('combobox', { name: '模型', exact: true })
  const effort = dialog.getByRole('combobox', { name: '思考强度', exact: true })
  for (const control of [question, model, effort, dialog.getByRole('button', { name: /关闭|close/i })]) await expect(control).toBeInViewport({ ratio: 1 })
  await expect(dialog.locator('.qa-sidebar')).toBeHidden()
  await dialog.getByRole('button', { name: '显示聊天记录', exact: true }).tap()
  await expect(dialog.locator('.qa-sidebar')).toBeVisible()
  await expect(dialog.locator('.qa-main')).toBeHidden()
  await dialog.getByRole('button', { name: '收起聊天记录', exact: true }).tap()
  await expect(question).toBeFocused()
  await effort.selectOption('high')
  await question.fill(longQuery)
  await dialog.getByRole('button', { name: '发送问题', exact: true }).tap()
  await expect(dialog.locator('.ai-markdown h2')).toHaveText('文档概要')
  await expect(dialog.locator('.ai-markdown pre code')).toContainText('long-code-')
  await expect(dialog.locator('.ai-markdown img')).toHaveCount(0)
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  expect(await dialog.locator('.qa-main').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  expect(await dialog.locator('.ai-markdown pre').evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true)
  for (const control of [question, model, effort, dialog.getByRole('button', { name: /关闭|close/i })]) await expect(control).toBeInViewport({ ratio: 1 })
  const toolCall = dialog.locator('details.qa-tool-call')
  const overview = toolCall.locator('.qa-tool-overview')
  await expect(overview).toBeHidden()
  await toolCall.locator('summary').tap()
  await expect(overview).toBeVisible()
  await expect(overview).toContainText(longQuery)
  await expect(overview).toContainText('已找到 2 篇文档')
  for (const container of [dialog, dialog.locator('.qa-main'), overview]) {
    expect(await container.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  }
  await expect(question).toBeInViewport({ ratio: 1 })
  const mobile = test.info().outputPath('assistant-mobile-320px.png')
  await dialog.screenshot({ path: mobile })
  await test.info().attach('assistant-mobile-320px', { path: mobile, contentType: 'image/png' })
  await toolCall.locator('summary').tap()
  await expect(overview).toBeHidden()
  await dialog.getByRole('button', { name: '显示聊天记录', exact: true }).tap()
  await expect(dialog.locator('.qa-session-select')).toHaveCount(1)
  const history = test.info().outputPath('assistant-mobile-history.png')
  await dialog.screenshot({ path: history })
  await test.info().attach('assistant-mobile-history', { path: history, contentType: 'image/png' })
  await dialog.locator('.qa-session-select').tap()
  await expect(question).toBeInViewport({ ratio: 1 })
  await expect(effort).toHaveValue('high')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(dialog.locator('.knowledge-assistant-dialog')).toBeInViewport({ ratio: 1 })
  await toolCall.locator('summary').tap()
  await expect(overview).toBeVisible()
  expect(await overview.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  const comfortable = test.info().outputPath('assistant-mobile-390px.png')
  await dialog.screenshot({ path: comfortable })
  await test.info().attach('assistant-mobile-390px', { path: comfortable, contentType: 'image/png' })
  await dialog.getByRole('button', { name: /关闭|close/i }).tap()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('status', { name: 'Note Bridge 已连接', exact: true })).toBeVisible()
  expect(frames.filter(frame => frame.type === 'pair')).toHaveLength(1)
  expect(frames.filter(frame => frame.method === 'messages.send')).toHaveLength(1)
  expect(frames.find(frame => frame.method === 'messages.send').params.effort).toBe('high')
  expect(frames.find(frame => frame.method === 'messages.send').params).not.toHaveProperty('context')
  expect(frames.some(frame => frame.method === 'runs.cancel')).toBe(false)
})
